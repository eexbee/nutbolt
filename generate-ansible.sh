w "roles/clamav/templates/security-scan.j2" <<'EOF'
#!/usr/bin/env bash
# security-scan - deployed by nutbolt (ansible)
# ClamAV scan with low CPU/IO priority. Exit: 0 clean, 1 infected, 2 error
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
TARGET="${1:-/}"
SCAN_CMD=(clamscan)
command -v clamdscan >/dev/null 2>&1 && clamdscan --ping 2>/dev/null && SCAN_CMD=(clamscan --multiscan --fdpass)
{% if security_scan_exclude_defaults | default(true) %}
EXCLUDES=(--exclude-dir="^/var/lib/mysql" --exclude-dir="^/var/lib/postgresql" \
          --exclude-dir="^/var/lib/docker" --exclude-dir="^/var/lib/containerd" \
          --exclude-dir="^/var/lib/minio" --exclude-dir="^/mnt/minio" --exclude-dir="^/srv/minio" \
          --exclude-dir="^/var/lib/redis")
{% else %}
EXCLUDES=()
{% endif %}
nice -n 19 ionice -c3 "${SCAN_CMD[@]}" --infected --recursive "${EXCLUDES[@]}" "$TARGET"
rc=$?
case $rc in
    0) echo "RESULT: CLEAN"; exit 0 ;;
    1) echo "RESULT: INFECTED FILES FOUND"; exit 1 ;;
    *) echo "RESULT: ERROR (exit $rc)"; exit 2 ;;
esac
EOF

