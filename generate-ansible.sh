#!/usr/bin/env bash
# =============================================================================
# generate-ansible.sh - Generate a ready-to-run Ansible project from the
# framework configuration (config/default.yml + config/servers/*.yml).
#
# Output:
#   ansible/inventory.ini
#   ansible/site.yml
#   ansible/group_vars/all.yml (+ per-profile group vars)
#   ansible/roles/{common,ssh,firewall,fail2ban,clamav,updates,sysctl,limits,
#                   docker,web,database,redis,minio}/
#
# Usage: ./generate-ansible.sh [-t target-dir] [-c config.yml]
# =============================================================================
set -u

FRAMEWORK_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export FRAMEWORK_ROOT

source "$FRAMEWORK_ROOT/lib/logging.sh"
source "$FRAMEWORK_ROOT/lib/common.sh"
source "$FRAMEWORK_ROOT/lib/os_detect.sh"
source "$FRAMEWORK_ROOT/lib/config_loader.sh"

TARGET="$FRAMEWORK_ROOT/ansible"
CONFIG_FILE=""

while getopts "t:c:h" opt; do
    case "$opt" in
        t) TARGET="$OPTARG" ;;
        c) CONFIG_FILE="$OPTARG" ;;
        h) grep '^#' "$0" | sed 's/^# \{0,2\}//'; exit 0 ;;
        *) exit 1 ;;
    esac
done

logging_init
log_section "GENERATING ANSIBLE PROJECT"

# config values drive group_vars defaults (framework runs on the control node,
# os_detect would fail here - do not call it)
OS_FAMILY="debian"

config_load_stack "$CONFIG_FILE"

SSH_PORT="$(config_get "ssh.port" 22222)"
SSH_MAXAUTH="$(config_get "ssh.max_auth_tries" 5)"
F2B_MAXRETRY="$(config_get "security.fail2ban.maxretry" 5)"
F2B_BANTIME="$(config_get "security.fail2ban.bantime" 1h)"
F2B_FINDTIME="$(config_get "security.fail2ban.findtime" 10m)"
NOFILE_DEFAULT="$(config_get "limits.nofile_default" 65535)"
NOFILE_DB="$(config_get "limits.nofile_database" 100000)"
NOFILE_MINIO="$(config_get "limits.nofile_minio" 200000)"
DOCKER_LOG_SIZE="$(config_get "profiles.docker.log_max_size" 10m)"
DOCKER_LOG_FILE="$(config_get "profiles.docker.log_max_file" 3)"

TCP_PORTS="$(config_get_list_csv "firewall.tcp_ports" "80 443")"
TCP_PORTS_YAML="$(config_get_list "firewall.tcp_ports" "80 443" | sed 's/^/      - /')"
UDP_PORTS_YAML="$(config_get_list "firewall.udp_ports" "" | sed 's/^/      - /')"
[[ -z "$UDP_PORTS_YAML" ]] && UDP_PORTS_YAML="      []"

mkdir -p "$TARGET"/{group_vars,host_vars}
ROLES="common ssh firewall fail2ban clamav updates sysctl limits docker web database redis minio"
for r in $ROLES; do
    mkdir -p "$TARGET/roles/$r/"{tasks,handlers,templates}
done

w() { # w <relative-path> ; content on stdin (overwrite)
    local f="$TARGET/$1"
    cat > "$f"
    log_ok "wrote: ansible/${1}"
}

# =============================================================================
# inventory.ini
# =============================================================================
w "inventory.ini" <<EOF
# =============================================================================
# Generated by nutbolt generate-ansible.sh
# Add your servers, then: ansible-playbook -i inventory.ini site.yml
# =============================================================================

[hardened:children]
web_servers
database_servers
redis_servers
minio_servers
docker_servers

[web_servers]
# web1.example.com ansible_host=203.0.113.10

[database_servers]
# db1.example.com ansible_host=203.0.113.20

[redis_servers]
# redis1.example.com ansible_host=203.0.113.30

[minio_servers]
# minio1.example.com ansible_host=203.0.113.40

[docker_servers]
# docker1.example.com ansible_host=203.0.113.50

[hardened:vars]
# ansible_user=admin
# ansible_ssh_port=$SSH_PORT
# ansible_become=true
EOF

# =============================================================================
# group_vars
# =============================================================================
w "group_vars/all.yml" <<EOF
# =============================================================================
# Global variables - generated from nutbolt configuration
# =============================================================================
ssh_port: $SSH_PORT
ssh_max_auth_tries: $SSH_MAXAUTH
ssh_disable_root_login: $(config_get ssh.disable_root_login true)
ssh_disable_password_auth: $(config_get ssh.disable_password_auth true)

firewall_enabled: $(config_get firewall.enabled true)
firewall_tcp_ports:
$TCP_PORTS_YAML
firewall_udp_ports:
$UDP_PORTS_YAML

security_fail2ban_enabled: $(config_get security.fail2ban.enabled true)
security_clamav_enabled: $(config_get security.clamav.enabled true)
security_updates_enabled: $(config_get security.updates.enabled true)
security_scan_exclude_defaults: $(config_get security.clamav.exclude_defaults true)

fail2ban_maxretry: $F2B_MAXRETRY
fail2ban_bantime: "$F2B_BANTIME"
fail2ban_findtime: "$F2B_FINDTIME"

limits_nofile_default: $NOFILE_DEFAULT
limits_nofile_database: $NOFILE_DB
limits_nofile_minio: $NOFILE_MINIO

docker_log_max_size: "$DOCKER_LOG_SIZE"
docker_log_max_file: "$DOCKER_LOG_FILE"

# profile switches (overridden per group)
profiles_web: false
profiles_database: false
profiles_redis: false
profiles_minio: false
profiles_docker: false
EOF

w "group_vars/web_servers.yml" <<'EOF'
profiles_web: true
EOF
w "group_vars/database_servers.yml" <<'EOF'
profiles_database: true
EOF
w "group_vars/redis_servers.yml" <<'EOF'
profiles_redis: true
EOF
w "group_vars/minio_servers.yml" <<'EOF'
profiles_minio: true
EOF
w "group_vars/docker_servers.yml" <<'EOF'
profiles_docker: true
EOF

w "host_vars/.gitkeep" </dev/null

