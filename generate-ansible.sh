w "roles/updates/tasks/main.yml" <<'EOF'
---
- name: Automatic updates (Debian)
  when: ansible_facts.os_family == 'Debian'
  block:
    - name: Install unattended-upgrades
      ansible.builtin.apt: { name: unattended-upgrades, state: present }

    - name: Enable auto upgrades
      ansible.builtin.copy:
        dest: /etc/apt/apt.conf.d/20auto-upgrades
        content: |
          APT::Periodic::Update-Package-Lists "1";
          APT::Periodic::Download-Upgradeable-Packages "1";
          APT::Periodic::Unattended-Upgrade "1";
          APT::Periodic::AutocleanInterval "7";

    - name: Security updates only - disable ${distro_codename}-updates origin
      ansible.builtin.replace:
        path: /etc/apt/apt.conf.d/50unattended-upgrades
        regexp: '(?m)^(\s*)"?\$\{distro_id\}:\$\{distro_codename\}-updates"?\s*;'
        replace: '// removed by nutbolt (security-only)'

    - name: Never reboot automatically
      ansible.builtin.copy:
        dest: /etc/apt/apt.conf.d/51nutbolt-noreboot
        content: 'Unattended-Upgrade::Automatic-Reboot "false";'

- name: Automatic updates (RHEL)
  when: ansible_facts.os_family == 'RedHat'
  block:
    - name: Install dnf-automatic
      ansible.builtin.dnf: { name: dnf-automatic, state: present }

    - name: Security updates only
      ansible.builtin.lineinfile:
        path: /etc/dnf/automatic.conf
        regexp: '^upgrade_type'
        line: 'upgrade_type = security'

    - name: Apply updates automatically
      ansible.builtin.lineinfile:
        path: /etc/dnf/automatic.conf
        regexp: '^apply_updates'
        line: 'apply_updates = yes'

    - name: Enable dnf-automatic timer
      ansible.builtin.systemd: { name: dnf-automatic.timer, state: started, enabled: true }
EOF

