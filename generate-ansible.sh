# roles: ssh
# =============================================================================
w "roles/ssh/tasks/main.yml" <<'EOF'
---
- name: Manage sshd options
  ansible.builtin.lineinfile:
    path: /etc/ssh/sshd_config
    regexp: "{{ item.regexp }}"
    line: "{{ item.line }}"
    validate: /usr/sbin/sshd -t -f %s
    backup: true
  loop:
    - { regexp: '^#?\\s*Port\\s+',                  line: 'Port {{ ssh_port }}' }
    - { regexp: '^#?\\s*MaxAuthTries\\s+',          line: 'MaxAuthTries {{ ssh_max_auth_tries }}' }
    - { regexp: '^#?\\s*PubkeyAuthentication\\s+',  line: 'PubkeyAuthentication yes' }
    - { regexp: '^#?\\s*PermitRootLogin\\s+',       line: 'PermitRootLogin {{ "no" if ssh_disable_root_login | bool else "prohibit-password" }}' }
    - { regexp: '^#?\\s*PasswordAuthentication\\s+', line: 'PasswordAuthentication {{ "no" if ssh_disable_password_auth | bool else "yes" }}' }
    - { regexp: '^#?\\s*KbdInteractiveAuthentication\\s+', line: 'KbdInteractiveAuthentication {{ "no" if ssh_disable_password_auth | bool else "yes" }}' }
  notify: validate and restart sshd

# Port is additive in sshd_config - ensure no duplicate Port lines remain
- name: Remove duplicate Port directives
  ansible.builtin.replace:
    path: /etc/ssh/sshd_config
    regexp: '(?m)^(Port {{ ssh_port }}\n)(?:Port .*\n)+'
    replace: '\g<1>'
  notify: validate and restart sshd

- name: Disable ssh socket activation (custom port + service mode)
  ansible.builtin.systemd:
    name: ssh.socket
    enabled: false
    state: stopped
  ignore_errors: true
  when: ansible_facts.os_family == 'Debian'
  notify: validate and restart sshd
EOF

w "roles/ssh/handlers/main.yml" <<'EOF'
---
- name: validate and restart sshd
  block:
    - name: Validate sshd configuration
      ansible.builtin.command: /usr/sbin/sshd -t
      changed_when: false
    - name: Restart sshd
      ansible.builtin.systemd:
        name: "{{ 'ssh' if ansible_facts.os_family == 'Debian' else 'sshd' }}"
        state: restarted
EOF

# =============================================================================
# roles: firewall
# =============================================================================
w "roles/firewall/tasks/main.yml" <<'EOF'
---
- name: Configure firewall with UFW (Debian)
  when: ansible_facts.os_family == 'Debian'
  block:
    - name: Install ufw
      ansible.builtin.apt: { name: ufw, state: present }

    - name: Allow SSH port before enabling
      community.general.ufw: { rule: allow, port: "{{ ssh_port }}", proto: tcp }

    - name: Allow configured TCP ports
      community.general.ufw:
        rule: allow
        port: "{{ item }}"
        proto: tcp
      loop: "{{ firewall_tcp_ports | default([]) }}"

    - name: Allow configured UDP ports
      community.general.ufw:
        rule: allow
        port: "{{ item }}"
        proto: udp
      loop: "{{ firewall_udp_ports | default([]) | difference(['[]']) }}"

    - name: Set default policies
      community.general.ufw: { direction: incoming, policy: deny }

    - name: Set outgoing policy
      community.general.ufw: { direction: outgoing, policy: allow }

    - name: Enable ufw
      community.general.ufw: { state: enabled }

- name: Configure firewall with firewalld (RHEL)
  when: ansible_facts.os_family == 'RedHat'
  block:
    - name: Install firewalld
      ansible.builtin.dnf: { name: firewalld, state: present }

    - name: Start and enable firewalld
      ansible.builtin.systemd: { name: firewalld, state: started, enabled: true }

    - name: Allow SSH port
      ansible.posix.firewalld:
        port: "{{ ssh_port }}/tcp"
        permanent: true
        immediate: true
        state: enabled

    - name: Allow configured TCP ports
      ansible.posix.firewalld:
        port: "{{ item }}/tcp"
        permanent: true
        immediate: true
        state: enabled
      loop: "{{ firewall_tcp_ports | default([]) }}"

    - name: Allow configured UDP ports
      ansible.posix.firewalld:
        port: "{{ item }}/udp"
        permanent: true
        immediate: true
        state: enabled
      loop: "{{ firewall_udp_ports | default([]) | difference(['[]']) }}"

    - name: Remove default ssh service (port 22) when port changed
      ansible.posix.firewalld:
        service: ssh
        permanent: true
        immediate: true
        state: "{{ 'disabled' if ssh_port | int != 22 else 'enabled' }}"
EOF

